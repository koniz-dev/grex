/// Icon size tokens (paired with text sizes so icons never look orphaned).
class AppIconSizes {
  AppIconSizes._();

  /// 14pt — inline with caption text.
  static const double xs = 14;

  /// 16pt — inline with body small.
  static const double sm = 16;

  /// 20pt — default UI icons (list rows, buttons).
  static const double md = 20;

  /// 24pt — app bar and primary action icons.
  static const double lg = 24;

  /// 32pt — section headers / cards.
  static const double xl = 32;

  /// 48pt — empty-state / hero illustrations.
  static const double hero = 48;

  /// 64pt — illustration centerpiece.
  static const double illustration = 64;
}
